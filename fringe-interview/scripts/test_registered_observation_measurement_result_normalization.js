const assert = require('assert');
const api = require('../src/core/observation');
const { buildNormalizationFixture } = require('./registered_observation_measurement_result_normalization_fixture');
const input = buildNormalizationFixture(), before = JSON.stringify(input);
const result = api.normalizeRegisteredObservationMeasurementResult(input);
assert.equal(result.status, 'calculated');
assert.equal(result.measurementId, input.measurement.id);
assert.equal(result.characteristicId, input.characteristicId);
assert.equal(result.observationRefs.length, 2);
assert.deepStrictEqual(result, api.normalizeRegisteredObservationMeasurementResult({ ...input, observations: [...input.observations].reverse() }));
assert(result.id.startsWith('measurement_result:') && result.id.length === 83);
assert.equal(result.calculatedBy, input.normalization.producerId);
assert.equal(result.extensions.normalization.version, input.normalization.version);
assert(api.validateRegisteredObservationMeasurementResult(result, input).valid);
assert(!api.validateRegisteredObservationMeasurementResult({ ...result, confidence: result.confidence + 0.01 }, input).valid);
assert(Object.isFrozen(result) && Object.isFrozen(result.observationRefs) && Object.isFrozen(result.extensions.normalization));
assert.equal(JSON.stringify(input), before);
input.observations[0].confidence = 0;
assert.notEqual(result.confidence, 0, 'result must not alias later input mutation');
const one = buildNormalizationFixture(); one.observations = [one.observations[0]];
assert.equal(api.normalizeRegisteredObservationMeasurementResult(one).status, 'calculated');
const empty = buildNormalizationFixture(); empty.observations = [];
const insufficient = api.normalizeRegisteredObservationMeasurementResult(empty);
assert.equal(insufficient.status, 'insufficient_data'); assert.equal(insufficient.normalizedValue, null); assert.equal(insufficient.direction, null);
const threshold = buildNormalizationFixture(); threshold.normalization.rules.minimumIndependentObservedSignals = 3;
assert.equal(api.normalizeRegisteredObservationMeasurementResult(threshold).status, 'insufficient_data');
const noUsefulWeight = buildNormalizationFixture(); noUsefulWeight.observations = noUsefulWeight.observations.map(item => ({ ...item, confidence: 0 }));
assert.equal(api.normalizeRegisteredObservationMeasurementResult(noUsefulWeight).status, 'insufficient_data');
console.log('Registered Observation Measurement Result Normalization tests PASSED');
